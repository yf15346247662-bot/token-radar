// Token Radar: a token-launch radar for token-radar-01 (Node 22, standard library only).
//
// The program reads the sealed DefiLlama snapshot (input/snapshot.json), scores every protocol
// that records no token and is not a wrapped, staked or bridged product of one that trades, and
// writes a ranked board to /output/board.json plus the dashboard's data, dashboard/ and
// screenshots/ and /output/dossier.json (via the vendored make.fun library).
//
// The board is the whole pre-token universe the snapshot can name: every protocol on the
// watchlist, plus every pre-token protocol below the watchlist floor that passes the same
// no-token rule. Protocols above the floor that the watchlist leaves out are set aside, not
// ranked: the snapshot names no parent protocol, so the watchlist is the record of which
// above-floor protocols pass the full rule, and a sub-product of a parent is not a launch of
// its own. Live-token protocols are set aside separately, with their market caps shown.
//
// Implied value is a model, never a promise, and it follows only from the snapshot's figures:
//
//   implied = round( tvl_usd x 0.30
//                      x (1 + clamp(change_7d, -50, 150) / 100 x 0.8)
//                      x (0.5 + min(age_days, 1460) / 1460 x 0.5)
//                      x (1 + 0.04 x min(max(chains - 1, 0), 5)) )
//
// TVL is the size of the launch, seven-day growth is its momentum, age is how long it has run
// with no token, and the chain count is how many chains the launch would reach. No protocol
// name is ever special-cased: one function scores every row.
//
// Outside the grader's container, MAKEFUN_OUTPUT_DIR stands in for /output:
//   mkdir -p out && MAKEFUN_OUTPUT_DIR=out node main.ts --input <snapshot.json|directory>

