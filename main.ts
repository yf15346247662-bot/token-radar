/** An http:// or https:// address where the gate refuses one: an HTML attribute value, a
 *  <style> body, an inline <script> import, a CSS file, or a JavaScript import, export-from,
 *  require or dynamic-import specifier. Visible text and comments may carry URLs. */
const NETWORK_ATTRIBUTE = /(?:src|href|action|poster|background|cite|data|formaction)\s*=\s*["']https?:\/\//i;
const NETWORK_STYLE = /<style[^>]*>[\s\S]*?https?:\/\//i;
const NETWORK_IMPORT = /(?:import|export\s+(?:\*|\{[^}]*\})\s+from|require\s*\(|import\s*\()\s*["']https?:\/\//;
const NETWORK_CSS_URL = /url\(\s*["']?https?:\/\//i;

/** Why the dashboard is not one the gate will take, or null: file count, bytes, and no network. */
export function dashboardIssue(dir: string): string | null {
  const names = readdirSync(dir).filter((n) => !n.startsWith('.'));
  if (names.length > 400) return `dashboard/ holds ${names.length} files, over the 400 the gate allows`;
  let total = 0;
  for (const name of names) {
    const path = join(dir, name);
    if (!statSync(path).isFile()) return `dashboard/${name} is not a regular file`;
    const bytes = readFileSync(path, 'utf8');
    total += Buffer.byteLength(bytes, 'utf8');
    if (name.endsWith('.html') && (NETWORK_ATTRIBUTE.test(bytes) || NETWORK_STYLE.test(bytes))) {
      return `dashboard/${name} names an http:// or https:// address`;
    }
    if (name.endsWith('.css') && NETWORK_CSS_URL.test(bytes)) return `dashboard/${name} names an http:// or https:// address`;
    if (name.endsWith('.js') && NETWORK_IMPORT.test(bytes)) return `dashboard/${name} names an http:// or https:// address`;
  }
  if (total > 4_194_304) return `dashboard/ is ${total} bytes, over the 4 MiB the gate allows`;
  return null;
}

/** --name <value> out of the arguments, or the fallback. */
function arg(name: string, fallback: string): string {
  const at = process.argv.indexOf(`--${name}`);
  if (at >= 0 && at + 1 < process.argv.length) return process.argv[at + 1]!;
  const withEquals = process.argv.find((a) => a.startsWith(`--${name}=`));
  return withEquals === undefined ? fallback : withEquals.slice(name.length + 3);
}

